-- ── 이관 3: Epic → Feature (기존 Epic 이슈는 공통 레이어가 아니라 Default 공간의 UNIT Feature 로 남긴다) ──
UPDATE SN_CIRA_CIRA_ISSUE_TYPE SET TYPE_NM = 'Feature', ICON = 'feature', DESCR = '기능 단위 (공통 · 공간)'
WHERE TYPE_NM = 'Epic';
UPDATE SN_CIRA_ISSUE i SET FEATURE_SCOPE = 'UNIT' FROM SN_CIRA_CIRA_ISSUE_TYPE t
WHERE t.OBJ_ID = i.ISSUE_TYPE_ID AND t.TYPE_NM = 'Feature' AND i.FEATURE_SCOPE IS NULL;

-- 프리셋 기본 보드 유형 (KANBAN | SCRUM | LIST)
ALTER TABLE SN_CIRA_PROJECT_TYPE ADD COLUMN IF NOT EXISTS BOARD_TYPE VARCHAR(20) NOT NULL DEFAULT 'KANBAN';
UPDATE SN_CIRA_PROJECT_TYPE SET BOARD_TYPE = 'SCRUM' WHERE upper(TYPE_NM) = 'SCRUM';

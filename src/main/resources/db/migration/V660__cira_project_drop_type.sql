-- V660: 프로젝트에서 타입을 뗀다. 타입(SN_CIRA_PROJECT_TYPE)은 작업 공간 스타터 프리셋일 뿐이고,
-- 프로젝트가 고른 타입은 V650 에서 기본 공간의 PRESET_TYPE_ID 로 옮겨졌다.
-- 혹시 V650 이후 기본 공간 PRESET_TYPE_ID 가 비었으면 프로젝트 값으로 채우고 지운다.
UPDATE SN_CIRA_SPACE s SET PRESET_TYPE_ID = p.PROJECT_TYPE_ID
FROM SN_CIRA_PROJECT p
WHERE s.PROJECT_ID = p.OBJ_ID AND s.IS_DEFAULT_YN = 'Y' AND s.PRESET_TYPE_ID IS NULL AND p.PROJECT_TYPE_ID IS NOT NULL;

DROP INDEX IF EXISTS idx_ciraProject_type;
ALTER TABLE SN_CIRA_PROJECT DROP COLUMN IF EXISTS PROJECT_TYPE_ID;
ALTER TABLE SN_CIRA_PROJECT DROP COLUMN IF EXISTS PROJECT_TYPE;

CREATE TABLE IF NOT EXISTS SN_STUDY_DOCUMENT
(
    OBJ_ID VARCHAR(100) NOT NULL,
    OWNER_ID VARCHAR(200) NOT NULL,
    TITLE VARCHAR(500) NOT NULL,
    FILE_NM VARCHAR(500) NOT NULL,
    FILE_SIZE BIGINT NOT NULL,
    STORAGE_KEY VARCHAR(500),
    PAGE_COUNT INTEGER,
    STATUS VARCHAR(20) NOT NULL,
    FAIL_REASON TEXT,
    PARSER_VERSION VARCHAR(20),
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_studyDocument PRIMARY KEY (OBJ_ID)
);

CREATE TABLE IF NOT EXISTS SN_STUDY_UPLOAD
(
    OBJ_ID VARCHAR(100) NOT NULL,
    OWNER_ID VARCHAR(200) NOT NULL,
    FILE_NM VARCHAR(500) NOT NULL,
    FILE_SIZE BIGINT NOT NULL,
    PART_COUNT INTEGER NOT NULL,
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_studyUpload PRIMARY KEY (OBJ_ID)
);

CREATE TABLE IF NOT EXISTS SN_STUDY_SECTION
(
    OBJ_ID VARCHAR(100) NOT NULL,
    DOCUMENT_ID VARCHAR(100) NOT NULL,
    PARENT_ID VARCHAR(100),
    SECTION_KEY VARCHAR(10) NOT NULL,
    LVL INTEGER NOT NULL,
    TITLE VARCHAR(1000) NOT NULL,
    ORD INTEGER NOT NULL,
    PAGE_NO INTEGER,
    ANCHOR_BLOCK_KEY VARCHAR(10),
    PAGE_SECTION_ID VARCHAR(100),
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_studySection PRIMARY KEY (OBJ_ID),
    CONSTRAINT fk_studySection_document FOREIGN KEY (DOCUMENT_ID) REFERENCES SN_STUDY_DOCUMENT (OBJ_ID)
);

CREATE TABLE IF NOT EXISTS SN_STUDY_BLOCK
(
    OBJ_ID VARCHAR(100) NOT NULL,
    DOCUMENT_ID VARCHAR(100) NOT NULL,
    SECTION_ID VARCHAR(100) NOT NULL,
    BLOCK_KEY VARCHAR(10) NOT NULL,
    PARENT_BLOCK_KEY VARCHAR(10),
    ORD INTEGER NOT NULL,
    BLOCK_TYP VARCHAR(20) NOT NULL,
    LVL INTEGER,
    BLOCK_TEXT TEXT,
    PAGE_NO INTEGER,
    ROW_IDX INTEGER,
    COL_IDX INTEGER,
    FIGURE_KEY VARCHAR(300),
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_studyBlock PRIMARY KEY (OBJ_ID),
    CONSTRAINT fk_studyBlock_document FOREIGN KEY (DOCUMENT_ID) REFERENCES SN_STUDY_DOCUMENT (OBJ_ID)
);

CREATE TABLE IF NOT EXISTS SN_STUDY_TERM
(
    OBJ_ID VARCHAR(100) NOT NULL,
    OWNER_ID VARCHAR(200) NOT NULL,
    DOCUMENT_ID VARCHAR(100),
    TERM VARCHAR(300) NOT NULL,
    NORM_TERM VARCHAR(300) NOT NULL,
    DEFINITION TEXT NOT NULL,
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_studyTerm PRIMARY KEY (OBJ_ID)
);

CREATE TABLE IF NOT EXISTS SN_STUDY_ANNOTATION
(
    OBJ_ID VARCHAR(100) NOT NULL,
    OWNER_ID VARCHAR(200) NOT NULL,
    DOCUMENT_ID VARCHAR(100) NOT NULL,
    START_BLOCK_KEY VARCHAR(10) NOT NULL,
    START_OFFSET INTEGER NOT NULL,
    END_BLOCK_KEY VARCHAR(10) NOT NULL,
    END_OFFSET INTEGER NOT NULL,
    QUOTE TEXT NOT NULL,
    COLOR VARCHAR(10) NOT NULL,
    NOTE TEXT,
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_studyAnnotation PRIMARY KEY (OBJ_ID),
    CONSTRAINT fk_studyAnnotation_document FOREIGN KEY (DOCUMENT_ID) REFERENCES SN_STUDY_DOCUMENT (OBJ_ID)
);

CREATE INDEX IF NOT EXISTS idx_studyDocument_owner ON SN_STUDY_DOCUMENT (OWNER_ID, CREATED_AT);
CREATE INDEX IF NOT EXISTS idx_studySection_doc ON SN_STUDY_SECTION (DOCUMENT_ID, ORD);
CREATE INDEX IF NOT EXISTS idx_studyBlock_doc_ord ON SN_STUDY_BLOCK (DOCUMENT_ID, ORD);
CREATE INDEX IF NOT EXISTS idx_studyBlock_doc_section ON SN_STUDY_BLOCK (DOCUMENT_ID, SECTION_ID);
CREATE UNIQUE INDEX IF NOT EXISTS uq_studyBlock_key ON SN_STUDY_BLOCK (DOCUMENT_ID, BLOCK_KEY);
CREATE INDEX IF NOT EXISTS idx_studyAnnotation_owner_doc ON SN_STUDY_ANNOTATION (OWNER_ID, DOCUMENT_ID);
CREATE UNIQUE INDEX IF NOT EXISTS uq_studyTerm_norm ON SN_STUDY_TERM (OWNER_ID, COALESCE(DOCUMENT_ID, ''), NORM_TERM);

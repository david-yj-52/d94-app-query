-- =============================================================
-- Docs 다중 Vault + CIRA Task ↔ Docs 연결 — 설계: DOCS 노트 "CIRA – Docs 통합 및 다중 Vault 설계"
-- (설계서는 V610 으로 적었으나 V610/V611 은 life-metric 이 먼저 썼다.)
-- SN_DOCS_VAULT: 엔티티(BaseModel). PRIVATE = 사용자 1인(OWNER_ID=이메일), TEAM = CIRA 프로젝트 1개.
-- SN_CIRA_ISSUE_DOC, SN_CIRA_DOC_RULE: JDBC 전용 (CiraDocsAccess).
-- =============================================================

CREATE TABLE IF NOT EXISTS SN_DOCS_VAULT
(
    OBJ_ID       VARCHAR(255) NOT NULL,
    VAULT_TYPE   VARCHAR(10)  NOT NULL, -- PRIVATE | TEAM
    NAME         VARCHAR(200) NOT NULL,
    OWNER_ID     VARCHAR(200),          -- PRIVATE: 사용자 이메일
    PROJECT_ID   VARCHAR(255),          -- TEAM: SN_CIRA_PROJECT.OBJ_ID
    SRV_ID       VARCHAR(50)  NOT NULL,
    TENANT       VARCHAR(50)  NOT NULL,
    TRACE_ID     VARCHAR(100) NOT NULL,
    EVNT_NM      VARCHAR(100) NOT NULL,
    PREV_EVNT_NM VARCHAR(100) NOT NULL,
    ACT_CD       VARCHAR(255),
    ACT_CM       VARCHAR(255),
    USE_STAT_CD  VARCHAR(40)  NOT NULL,
    CREATED_AT   TIMESTAMP,
    MODIFIED_AT  TIMESTAMP,
    CREATED_BY   VARCHAR(255),
    MODIFIED_BY  VARCHAR(255),
    CONSTRAINT pk_docsVault PRIMARY KEY (OBJ_ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_docsVault_private ON SN_DOCS_VAULT (TENANT, OWNER_ID) WHERE VAULT_TYPE = 'PRIVATE';
CREATE UNIQUE INDEX IF NOT EXISTS ux_docsVault_project ON SN_DOCS_VAULT (PROJECT_ID) WHERE PROJECT_ID IS NOT NULL;

-- 기존 사용자마다 PRIVATE vault 1개
INSERT INTO SN_DOCS_VAULT (OBJ_ID, VAULT_TYPE, NAME, OWNER_ID, SRV_ID, TENANT, TRACE_ID, EVNT_NM, PREV_EVNT_NM,
                           USE_STAT_CD, CREATED_AT, MODIFIED_AT)
SELECT gen_random_uuid()::text, 'PRIVATE', 'Private', o.OWNER_ID, 'd94-query', o.TENANT, 'V620', 'CreateDocsVault',
       'None', 'Usable', now(), now()
FROM (SELECT TENANT, OWNER_ID FROM SN_DOCS_FOLDER UNION SELECT TENANT, OWNER_ID FROM SN_DOCS_NOTE) o
ON CONFLICT DO NOTHING;

-- 폴더·노트에 VAULT_ID (OWNER_ID 는 만든 사람으로 남긴다)
ALTER TABLE SN_DOCS_FOLDER ADD COLUMN IF NOT EXISTS VAULT_ID VARCHAR(255);
ALTER TABLE SN_DOCS_NOTE ADD COLUMN IF NOT EXISTS VAULT_ID VARCHAR(255);
UPDATE SN_DOCS_FOLDER f SET VAULT_ID = v.OBJ_ID FROM SN_DOCS_VAULT v
WHERE f.VAULT_ID IS NULL AND v.VAULT_TYPE = 'PRIVATE' AND v.TENANT = f.TENANT AND v.OWNER_ID = f.OWNER_ID;
UPDATE SN_DOCS_NOTE n SET VAULT_ID = v.OBJ_ID FROM SN_DOCS_VAULT v
WHERE n.VAULT_ID IS NULL AND v.VAULT_TYPE = 'PRIVATE' AND v.TENANT = n.TENANT AND v.OWNER_ID = n.OWNER_ID;
ALTER TABLE SN_DOCS_FOLDER ALTER COLUMN VAULT_ID SET NOT NULL;
ALTER TABLE SN_DOCS_NOTE ALTER COLUMN VAULT_ID SET NOT NULL;
ALTER TABLE SN_DOCS_FOLDER DROP CONSTRAINT IF EXISTS fk_docsFolder_vault;
ALTER TABLE SN_DOCS_FOLDER ADD CONSTRAINT fk_docsFolder_vault FOREIGN KEY (VAULT_ID) REFERENCES SN_DOCS_VAULT (OBJ_ID);
ALTER TABLE SN_DOCS_NOTE DROP CONSTRAINT IF EXISTS fk_docsNote_vault;
ALTER TABLE SN_DOCS_NOTE ADD CONSTRAINT fk_docsNote_vault FOREIGN KEY (VAULT_ID) REFERENCES SN_DOCS_VAULT (OBJ_ID);

-- 유일성: 소유자 → vault 단위 (다른 vault 끼리는 같은 제목·폴더 이름 허용)
DROP INDEX IF EXISTS ux_docsFolder_name;
DROP INDEX IF EXISTS ux_docsNote_title;
CREATE UNIQUE INDEX IF NOT EXISTS ux_docsFolder_vaultName ON SN_DOCS_FOLDER (TENANT, VAULT_ID, COALESCE(PARENT_ID, ''), NAME);
CREATE UNIQUE INDEX IF NOT EXISTS ux_docsNote_vaultTitle ON SN_DOCS_NOTE (TENANT, VAULT_ID, TITLE);

-- CIRA Task ↔ Docs 노트. MAIN 은 Task 당 1개, DERIVED 는 여러 개. 노트를 지우면 연결도 사라진다.
CREATE TABLE IF NOT EXISTS SN_CIRA_ISSUE_DOC
(
    ISSUE_ID   VARCHAR(255) NOT NULL REFERENCES SN_CIRA_ISSUE (OBJ_ID),
    NOTE_ID    VARCHAR(255) NOT NULL REFERENCES SN_DOCS_NOTE (OBJ_ID) ON DELETE CASCADE,
    DOC_ROLE   VARCHAR(10)  NOT NULL, -- MAIN | DERIVED
    RULE_ID    VARCHAR(255),
    CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_ciraIssueDoc PRIMARY KEY (ISSUE_ID, NOTE_ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ciraIssueDoc_main ON SN_CIRA_ISSUE_DOC (ISSUE_ID) WHERE DOC_ROLE = 'MAIN';
CREATE INDEX IF NOT EXISTS idx_ciraIssueDoc_note ON SN_CIRA_ISSUE_DOC (NOTE_ID);

-- 프로젝트 · Task 타입별 파생 문서 폴더 슬롯
CREATE TABLE IF NOT EXISTS SN_CIRA_DOC_RULE
(
    OBJ_ID           VARCHAR(255) NOT NULL,
    PROJECT_ID       VARCHAR(255) NOT NULL REFERENCES SN_CIRA_PROJECT (OBJ_ID),
    ISSUE_TYPE_ID    VARCHAR(255) NOT NULL REFERENCES SN_CIRA_CIRA_ISSUE_TYPE (OBJ_ID),
    FOLDER_NAME      VARCHAR(200) NOT NULL,
    SORT_ORDER       INTEGER      NOT NULL DEFAULT 0,
    DEFAULT_KIND     VARCHAR(20),
    DEFAULT_STREAM   VARCHAR(50),
    TEMPLATE_CONTENT TEXT,
    AUTO_CREATE_YN   CHAR(1)      NOT NULL DEFAULT 'N',
    CONSTRAINT pk_ciraDocRule PRIMARY KEY (OBJ_ID),
    CONSTRAINT ux_ciraDocRule UNIQUE (PROJECT_ID, ISSUE_TYPE_ID, FOLDER_NAME)
);

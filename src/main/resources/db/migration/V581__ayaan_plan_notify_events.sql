-- ayaan 계획 알림 이벤트를 ayaan.NOTIFY_EVENTS(SN_SETTING, V545 이관 후)에 추가.
-- 사용자가 바꾼 값은 유지하고 없는 이벤트만 덧붙인다.

UPDATE SN_SETTING
SET SETTING_VALUE = CASE WHEN SETTING_VALUE = '' THEN 'PLAN_STARTED' ELSE SETTING_VALUE || ',PLAN_STARTED' END,
    MODIFIED_AT = now(), MODIFIED_BY = 'flyway'
WHERE SETTING_KEY = 'ayaan.NOTIFY_EVENTS' AND ',' || SETTING_VALUE || ',' NOT LIKE '%,PLAN_STARTED,%';

UPDATE SN_SETTING
SET SETTING_VALUE = CASE WHEN SETTING_VALUE = '' THEN 'PLAN_HALTED' ELSE SETTING_VALUE || ',PLAN_HALTED' END,
    MODIFIED_AT = now(), MODIFIED_BY = 'flyway'
WHERE SETTING_KEY = 'ayaan.NOTIFY_EVENTS' AND ',' || SETTING_VALUE || ',' NOT LIKE '%,PLAN_HALTED,%';

UPDATE SN_SETTING
SET SETTING_VALUE = CASE WHEN SETTING_VALUE = '' THEN 'PLAN_DEPLOYED' ELSE SETTING_VALUE || ',PLAN_DEPLOYED' END,
    MODIFIED_AT = now(), MODIFIED_BY = 'flyway'
WHERE SETTING_KEY = 'ayaan.NOTIFY_EVENTS' AND ',' || SETTING_VALUE || ',' NOT LIKE '%,PLAN_DEPLOYED,%';

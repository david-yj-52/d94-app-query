CREATE TABLE SN_STUDY_DICTIONARY_KEY (
    OWNER_ID VARCHAR(200) PRIMARY KEY,
    API_KEY VARCHAR(500) NOT NULL,
    REFERENCE VARCHAR(20) NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE SN_STUDY_DICTIONARY (
    OWNER_ID VARCHAR(200) NOT NULL,
    WORD VARCHAR(50) NOT NULL,
    REFERENCE VARCHAR(20) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    PAYLOAD JSONB NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (OWNER_ID, WORD, REFERENCE)
);
CREATE TABLE SN_STUDY_SYNTAX (
    DOCUMENT_ID VARCHAR(100) NOT NULL,
    SECTION_ID VARCHAR(100) NOT NULL,
    ANALYZER_VERSION VARCHAR(100) NOT NULL,
    PAYLOAD JSONB NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (DOCUMENT_ID, SECTION_ID, ANALYZER_VERSION)
);

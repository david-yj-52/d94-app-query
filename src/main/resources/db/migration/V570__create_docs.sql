-- 원천: SN_DOCS_FOLDER, SN_DOCS_NOTE (엔티티, BaseModel)
-- 버전·색인: SN_DOCS_NOTE_VER, SN_DOCS_LINK, SN_DOCS_TAG, SN_DOCS_TASK (JDBC 전용, 노트 삭제 시 CASCADE)
-- BaseModel 컬럼 길이는 엔티티와 같게 둔다 (ddl-auto=update 가 엔티티 기준으로 ALTER 하므로).
-- =============================================================

CREATE TABLE IF NOT EXISTS SN_DOCS_FOLDER
(
    OBJ_ID       VARCHAR(255) NOT NULL,
    OWNER_ID     VARCHAR(200) NOT NULL,
    PARENT_ID    VARCHAR(255),
    NAME         VARCHAR(200) NOT NULL,
    SORT_ORDER   INTEGER      NOT NULL DEFAULT 0,
    SRV_ID       VARCHAR(50)  NOT NULL,
    TENANT       VARCHAR(50)  NOT NULL,
    TRACE_ID     VARCHAR(100) NOT NULL,
    EVNT_NM      VARCHAR(100) NOT NULL,
    PREV_EVNT_NM VARCHAR(100) NOT NULL,
    ACT_CD       VARCHAR(255),
    ACT_CM       VARCHAR(255),
    USE_STAT_CD  VARCHAR(40)  NOT NULL,
    CREATED_AT   TIMESTAMP,
    MODIFIED_AT  TIMESTAMP,
    CREATED_BY   VARCHAR(255),
    MODIFIED_BY  VARCHAR(255),
    CONSTRAINT pk_docsFolder PRIMARY KEY (OBJ_ID),
    CONSTRAINT fk_docsFolder_parent FOREIGN KEY (PARENT_ID) REFERENCES SN_DOCS_FOLDER (OBJ_ID)
);
-- 같은 상위 폴더 안에서 이름 유일 (최상위는 PARENT_ID NULL → '' 로 비교)
CREATE UNIQUE INDEX IF NOT EXISTS ux_docsFolder_name ON SN_DOCS_FOLDER (TENANT, OWNER_ID, COALESCE(PARENT_ID, ''), NAME);

CREATE TABLE IF NOT EXISTS SN_DOCS_NOTE
(
    OBJ_ID       VARCHAR(255) NOT NULL,
    OWNER_ID     VARCHAR(200) NOT NULL,
    FOLDER_ID    VARCHAR(255),
    TITLE        VARCHAR(500) NOT NULL,
    CONTENT      TEXT,
    KIND         VARCHAR(20)  NOT NULL DEFAULT 'idea',
    STREAM       VARCHAR(50),
    VERSION      INTEGER      NOT NULL DEFAULT 1,
    SRV_ID       VARCHAR(50)  NOT NULL,
    TENANT       VARCHAR(50)  NOT NULL,
    TRACE_ID     VARCHAR(100) NOT NULL,
    EVNT_NM      VARCHAR(100) NOT NULL,
    PREV_EVNT_NM VARCHAR(100) NOT NULL,
    ACT_CD       VARCHAR(255),
    ACT_CM       VARCHAR(255),
    USE_STAT_CD  VARCHAR(40)  NOT NULL,
    CREATED_AT   TIMESTAMP,
    MODIFIED_AT  TIMESTAMP,
    CREATED_BY   VARCHAR(255),
    MODIFIED_BY  VARCHAR(255),
    CONSTRAINT pk_docsNote PRIMARY KEY (OBJ_ID),
    CONSTRAINT fk_docsNote_folder FOREIGN KEY (FOLDER_ID) REFERENCES SN_DOCS_FOLDER (OBJ_ID)
);
-- [[제목]] 링크의 키: vault(소유자) 안에서 제목 유일
CREATE UNIQUE INDEX IF NOT EXISTS ux_docsNote_title ON SN_DOCS_NOTE (TENANT, OWNER_ID, TITLE);
CREATE INDEX IF NOT EXISTS idx_docsNote_folder ON SN_DOCS_NOTE (FOLDER_ID);

CREATE TABLE IF NOT EXISTS SN_DOCS_NOTE_VER
(
    NOTE_ID   VARCHAR(255) NOT NULL REFERENCES SN_DOCS_NOTE (OBJ_ID) ON DELETE CASCADE,
    VERSION   INTEGER      NOT NULL,
    TITLE     VARCHAR(500) NOT NULL,
    CONTENT   TEXT,
    EDITED_BY VARCHAR(200),
    EDITED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_docsNoteVer PRIMARY KEY (NOTE_ID, VERSION)
);

-- 본문에서 뽑은 링크. 대상은 제목으로 저장하고 조회 때 같은 소유자의 노트와 맞춘다(없는 노트 링크 허용).
CREATE TABLE IF NOT EXISTS SN_DOCS_LINK
(
    FROM_ID  VARCHAR(255) NOT NULL REFERENCES SN_DOCS_NOTE (OBJ_ID) ON DELETE CASCADE,
    TO_TITLE VARCHAR(500) NOT NULL,
    REL      VARCHAR(10)  NOT NULL, -- link | origin
    CONSTRAINT pk_docsLink PRIMARY KEY (FROM_ID, TO_TITLE, REL)
);
CREATE INDEX IF NOT EXISTS idx_docsLink_toTitle ON SN_DOCS_LINK (TO_TITLE);

CREATE TABLE IF NOT EXISTS SN_DOCS_TAG
(
    NOTE_ID VARCHAR(255) NOT NULL REFERENCES SN_DOCS_NOTE (OBJ_ID) ON DELETE CASCADE,
    TAG     VARCHAR(200) NOT NULL,
    CONSTRAINT pk_docsTag PRIMARY KEY (NOTE_ID, TAG)
);
CREATE INDEX IF NOT EXISTS idx_docsTag_tag ON SN_DOCS_TAG (TAG);

-- 본문의 체크박스 줄. LINE_NO 는 0부터, 본문 줄 번호
CREATE TABLE IF NOT EXISTS SN_DOCS_TASK
(
    NOTE_ID VARCHAR(255) NOT NULL REFERENCES SN_DOCS_NOTE (OBJ_ID) ON DELETE CASCADE,
    LINE_NO INTEGER      NOT NULL,
    TEXT    TEXT         NOT NULL,
    STATUS  VARCHAR(10)  NOT NULL, -- todo | doing | done
    DUE_DT  DATE,
    CONSTRAINT pk_docsTask PRIMARY KEY (NOTE_ID, LINE_NO)
);

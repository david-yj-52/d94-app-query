-- 이슈당 활성 작업은 1건
CREATE UNIQUE INDEX IF NOT EXISTS ux_ayn_task_active_issue ON SN_AYN_TASK (ISSUE_KEY)
    WHERE STATUS IN ('QUEUED', 'RUNNING', 'PAUSED') AND ISSUE_KEY IS NOT NULL;
-- 작업공간(WORKSPACE_PATH)당 RUNNING 은 1건 (동시 선점·transition 경쟁의 최종 방어선)
CREATE UNIQUE INDEX IF NOT EXISTS ux_ayn_task_running_ws ON SN_AYN_TASK (WORKSPACE_PATH)
    WHERE STATUS = 'RUNNING';
CREATE INDEX IF NOT EXISTS ix_ayn_task_claim ON SN_AYN_TASK (TOOL_CD, STATUS, RESUME_AT);
CREATE INDEX IF NOT EXISTS ix_ayn_run_task ON SN_AYN_TASK_RUN (TASK_ID, RUN_SEQ);


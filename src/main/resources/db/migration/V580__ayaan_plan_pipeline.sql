-- ayaan 계획 파이프라인: 저장소 매핑 + 마일스톤 계획

CREATE TABLE IF NOT EXISTS SN_AYN_WORKSPACE_REPO
(
    PROJECT_KEY VARCHAR(50) NOT NULL,
    REPO_NM VARCHAR(100) NOT NULL,
    GIT_URL VARCHAR(500) NOT NULL,
    BASE_BRANCH VARCHAR(100) NOT NULL DEFAULT 'main',
    DEPLOY_BRANCH VARCHAR(100),
    SORT_ORD SMALLINT NOT NULL DEFAULT 0,
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_aynWorkspaceRepo PRIMARY KEY (PROJECT_KEY, REPO_NM),
    CONSTRAINT fk_aynWorkspaceRepo_ws FOREIGN KEY (PROJECT_KEY) REFERENCES SN_AYN_WORKSPACE (PROJECT_KEY)
);

CREATE TABLE IF NOT EXISTS SN_AYN_PLAN
(
    OBJ_ID VARCHAR(100) NOT NULL,
    PROJECT_KEY VARCHAR(50) NOT NULL,
    MILESTONE_ID VARCHAR(100) NOT NULL,
    MILESTONE_KEY VARCHAR(60),
    STAGE VARCHAR(20) NOT NULL,
    CURRENT_ISSUE_KEY VARCHAR(100),
    LAST_ERROR TEXT,
    STARTED_AT TIMESTAMP,
    ENDED_AT TIMESTAMP,
    SRV_ID VARCHAR(100),
    TENANT VARCHAR(100),
    TRACE_ID VARCHAR(100),
    EVNT_NM VARCHAR(100),
    PREV_EVNT_NM VARCHAR(100),
    ACT_CD VARCHAR(100),
    ACT_CM VARCHAR(255),
    USE_STAT_CD VARCHAR(20),
    CREATED_AT TIMESTAMP,
    MODIFIED_AT TIMESTAMP,
    CREATED_BY VARCHAR(100),
    MODIFIED_BY VARCHAR(100),
    CONSTRAINT pk_aynPlan PRIMARY KEY (OBJ_ID)
);

-- 프로젝트당 진행 중 계획은 하나
CREATE UNIQUE INDEX IF NOT EXISTS ux_ayn_plan_active ON SN_AYN_PLAN (PROJECT_KEY) WHERE STAGE NOT IN ('DONE', 'CANCELLED');

ALTER TABLE SN_AYN_TASK ADD COLUMN IF NOT EXISTS PLAN_ID VARCHAR(100);
ALTER TABLE SN_AYN_WORKSPACE ALTER COLUMN WORKSPACE_PATH DROP NOT NULL;

-- =============================================================
-- infra (통합 리소스·사용량 관리) — 설계: DOCS "D94 통합 리소스 및 사용량 관리 서비스 설계서"
-- 설계서의 V630 은 cira-space 가 써서 V640 으로 둔다.
-- 전부 JdbcTemplate 전용(엔티티 없음). 노드 삭제 시 서비스·스냅샷 CASCADE.
-- 민감 자격 증명(비밀번호·개인키)은 저장하지 않는다 — SSH 별칭·키 경로 힌트 같은 메타정보만.
-- =============================================================

CREATE TABLE IF NOT EXISTS SN_INFRA_NODE
(
    ID               BIGSERIAL PRIMARY KEY,
    TENANT           VARCHAR(50)  NOT NULL,
    NODE_KEY         VARCHAR(50)  NOT NULL,
    NAME             VARCHAR(200) NOT NULL,
    NODE_TYPE        VARCHAR(20)  NOT NULL, -- HOME_PC|CLOUD_VM|EDGE_GPU|MCU|SERVERLESS
    LOCATION         VARCHAR(20)  NOT NULL, -- HOME_LAN|OCI|VERCEL
    STATUS           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE|PLANNED|MAINTENANCE
    OS_INFO          VARCHAR(200),
    CPU_MODEL        VARCHAR(200),
    CPU_CORES        INTEGER,
    MEMORY_TOTAL_MB  INTEGER,
    GPU_MODEL        VARCHAR(200),
    GPU_MEMORY_MB    INTEGER,
    DISK_TOTAL_GB    INTEGER,
    SPECS_EXTRA_JSON TEXT,
    HOST_LABEL       VARCHAR(200),
    SSH_ALIAS        VARCHAR(100),
    SSH_USER         VARCHAR(100),
    SSH_PORT         INTEGER,
    SSH_KEY_HINT     VARCHAR(300),
    ACCESS_NOTES     TEXT,
    LAST_SEEN_AT     TIMESTAMPTZ,
    CREATED_AT       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UPDATED_AT       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_infraNode_key UNIQUE (TENANT, NODE_KEY)
);

CREATE TABLE IF NOT EXISTS SN_INFRA_SERVICE
(
    ID               BIGSERIAL PRIMARY KEY,
    NODE_ID          BIGINT       NOT NULL REFERENCES SN_INFRA_NODE (ID) ON DELETE CASCADE,
    NAME             VARCHAR(200) NOT NULL,
    KIND             VARCHAR(20)  NOT NULL, -- DOCKER|SYSTEMD|FIRMWARE|HOSTED
    PORTS_TEXT       VARCHAR(200),
    ENDPOINT_URL     VARCHAR(500),
    COMPOSE_PATH     VARCHAR(500),
    ESTIMATED_MEM_MB INTEGER,
    DESCRIPTION      TEXT
);
CREATE INDEX IF NOT EXISTS ix_infraService_node ON SN_INFRA_SERVICE (NODE_ID);

CREATE TABLE IF NOT EXISTS SN_INFRA_METRIC_SNAPSHOT
(
    ID               BIGSERIAL PRIMARY KEY,
    NODE_ID          BIGINT      NOT NULL REFERENCES SN_INFRA_NODE (ID) ON DELETE CASCADE,
    COLLECTED_AT     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CPU_PCT          DOUBLE PRECISION,
    MEM_USED_MB      INTEGER,
    MEM_AVAILABLE_MB INTEGER,
    MEM_PCT          DOUBLE PRECISION,
    SWAP_USED_MB     INTEGER,
    DISK_USED_GB     DOUBLE PRECISION,
    DISK_PCT         DOUBLE PRECISION,
    GPU_UTIL_PCT     DOUBLE PRECISION,
    GPU_MEM_USED_MB  INTEGER,
    LOAD_AVG_1M      DOUBLE PRECISION,
    UPTIME_SEC       BIGINT,
    EXTRA_JSON       TEXT
);
CREATE INDEX IF NOT EXISTS ix_infraMetric_node_at ON SN_INFRA_METRIC_SNAPSHOT (NODE_ID, COLLECTED_AT DESC);
CREATE INDEX IF NOT EXISTS ix_infraMetric_at ON SN_INFRA_METRIC_SNAPSHOT (COLLECTED_AT);

CREATE TABLE IF NOT EXISTS SN_INFRA_PROCESS_SNAPSHOT
(
    ID           BIGSERIAL PRIMARY KEY,
    SNAPSHOT_ID  BIGINT       NOT NULL REFERENCES SN_INFRA_METRIC_SNAPSHOT (ID) ON DELETE CASCADE,
    NODE_ID      BIGINT       NOT NULL,
    COLLECTED_AT TIMESTAMPTZ  NOT NULL,
    PID          INTEGER,
    PROC_NAME    VARCHAR(200) NOT NULL,
    PROC_TYPE    VARCHAR(20)  NOT NULL, -- PROCESS|CONTAINER
    MEM_RSS_MB   DOUBLE PRECISION,
    MEM_PCT      DOUBLE PRECISION,
    CPU_PCT      DOUBLE PRECISION,
    COMMAND_LINE VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS ix_infraProcess_snapshot ON SN_INFRA_PROCESS_SNAPSHOT (SNAPSHOT_ID);

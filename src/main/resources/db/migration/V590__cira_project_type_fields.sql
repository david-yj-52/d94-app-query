-- 필드 키: 기본 필드 'sys:<name>' (코드 카탈로그), 사용자 정의 필드 'cf:<SN_CIRA_CUSTOM_FIELD.OBJ_ID>'
-- ponytail: JdbcTemplate 전용 테이블이라 BaseModel 칼럼 중 OBJ_ID·TENANT·CREATED_AT·MODIFIED_AT 만 둔다

CREATE TABLE IF NOT EXISTS SN_CIRA_PROJECT_TYPE
(
    OBJ_ID      VARCHAR(100) NOT NULL,
    TENANT      VARCHAR(100) NOT NULL,
    TYPE_NM     VARCHAR(30)  NOT NULL,
    DESCR       VARCHAR(500),
    SORT_ORD    SMALLINT     NOT NULL DEFAULT 0,
    CREATED_AT  TIMESTAMP    NOT NULL DEFAULT now(),
    MODIFIED_AT TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT pk_ciraProjectType PRIMARY KEY (OBJ_ID),
    CONSTRAINT uk_ciraProjectType_01 UNIQUE (TENANT, TYPE_NM)
);

CREATE TABLE IF NOT EXISTS SN_CIRA_PROJECT_TYPE_FIELD
(
    OBJ_ID             VARCHAR(100) NOT NULL DEFAULT gen_random_uuid()::text,
    PROJECT_TYPE_ID    VARCHAR(100) NOT NULL,
    FIELD_KEY          VARCHAR(120) NOT NULL,
    SORT_ORD           SMALLINT     NOT NULL DEFAULT 0,
    DEFAULT_VISIBLE_YN VARCHAR(1)   NOT NULL DEFAULT 'Y',
    CONSTRAINT pk_ciraProjectTypeField PRIMARY KEY (OBJ_ID),
    CONSTRAINT uk_ciraProjectTypeField_01 UNIQUE (PROJECT_TYPE_ID, FIELD_KEY),
    CONSTRAINT fk_ciraProjectTypeField_type FOREIGN KEY (PROJECT_TYPE_ID) REFERENCES SN_CIRA_PROJECT_TYPE (OBJ_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SN_CIRA_PROJECT_FIELD
(
    OBJ_ID     VARCHAR(100) NOT NULL DEFAULT gen_random_uuid()::text,
    PROJECT_ID VARCHAR(100) NOT NULL,
    FIELD_KEY  VARCHAR(120) NOT NULL,
    SORT_ORD   SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT pk_ciraProjectField PRIMARY KEY (OBJ_ID),
    CONSTRAINT uk_ciraProjectField_01 UNIQUE (PROJECT_ID, FIELD_KEY),
    CONSTRAINT fk_ciraProjectField_project FOREIGN KEY (PROJECT_ID) REFERENCES SN_CIRA_PROJECT (OBJ_ID)
);

CREATE TABLE IF NOT EXISTS SN_CIRA_USER_COLUMN_PREF
(
    OBJ_ID      VARCHAR(100) NOT NULL DEFAULT gen_random_uuid()::text,
    USER_ID     VARCHAR(100) NOT NULL,
    PROJECT_ID  VARCHAR(100) NOT NULL,
    FIELD_KEYS  JSONB        NOT NULL,
    KNOWN_KEYS  JSONB        NOT NULL,
    MODIFIED_AT TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT pk_ciraUserColumnPref PRIMARY KEY (OBJ_ID),
    CONSTRAINT uk_ciraUserColumnPref_01 UNIQUE (USER_ID, PROJECT_ID),
    CONSTRAINT fk_ciraUserColumnPref_project FOREIGN KEY (PROJECT_ID) REFERENCES SN_CIRA_PROJECT (OBJ_ID)
);

ALTER TABLE SN_CIRA_PROJECT ADD COLUMN IF NOT EXISTS PROJECT_TYPE_ID VARCHAR(100)
    REFERENCES SN_CIRA_PROJECT_TYPE (OBJ_ID);

-- 이관 1: 기준정보 cira.project.types + 기존 프로젝트 타입 문자열 + 기본 SCRUM·KANBAN → 타입 행
WITH names AS (
    SELECT TENANT, jsonb_array_elements_text(SETTING_VALUE::jsonb) AS TYPE_NM
    FROM SN_SETTING
    WHERE SETTING_KEY = 'cira.project.types' AND SETTING_VALUE LIKE '[%'
    UNION
    SELECT TENANT, PROJECT_TYPE FROM SN_CIRA_PROJECT WHERE TENANT IS NOT NULL
    UNION
    SELECT t.TENANT, d.TYPE_NM
    FROM (SELECT DISTINCT TENANT FROM SN_CIRA_PROJECT WHERE TENANT IS NOT NULL
          UNION SELECT 'TSH') t
         CROSS JOIN (VALUES ('SCRUM'), ('KANBAN')) d(TYPE_NM)
)
INSERT INTO SN_CIRA_PROJECT_TYPE (OBJ_ID, TENANT, TYPE_NM, SORT_ORD)
SELECT gen_random_uuid()::text, TENANT, left(trim(TYPE_NM), 30),
       (row_number() OVER (PARTITION BY TENANT ORDER BY TYPE_NM))::smallint
FROM names
WHERE trim(TYPE_NM) <> ''
ON CONFLICT (TENANT, TYPE_NM) DO NOTHING;

-- 이관 2: 기본 세트 = 지금 화면 컬럼 (우선순위·담당자·수정일). SCRUM 은 스프린트·스토리 포인트(기본 숨김) 추가
INSERT INTO SN_CIRA_PROJECT_TYPE_FIELD (PROJECT_TYPE_ID, FIELD_KEY, SORT_ORD, DEFAULT_VISIBLE_YN)
SELECT t.OBJ_ID, f.FIELD_KEY, f.SORT_ORD, f.VIS
FROM SN_CIRA_PROJECT_TYPE t
     CROSS JOIN (VALUES ('sys:priority', 1, 'Y'), ('sys:assignee', 2, 'Y'), ('sys:modifiedAt', 3, 'Y'),
                        ('sys:sprint', 4, 'N'), ('sys:storyPoints', 5, 'N')) f(FIELD_KEY, SORT_ORD, VIS)
WHERE f.SORT_ORD <= 3 OR t.TYPE_NM = 'SCRUM'
ON CONFLICT (PROJECT_TYPE_ID, FIELD_KEY) DO NOTHING;

-- 이관 3: 프로젝트 → 타입 ID
UPDATE SN_CIRA_PROJECT p
SET PROJECT_TYPE_ID = t.OBJ_ID
FROM SN_CIRA_PROJECT_TYPE t
WHERE p.PROJECT_TYPE_ID IS NULL AND t.TENANT = p.TENANT AND t.TYPE_NM = left(trim(p.PROJECT_TYPE), 30);

-- 이관 4: 기준정보 키는 타입 테이블로 대체됨
DELETE FROM SN_SETTING WHERE SETTING_KEY = 'cira.project.types';

-- 이관 5: Task 세부 유형 'Task' → 'Issue'
UPDATE SN_CIRA_CIRA_ISSUE_TYPE
SET TYPE_NM = 'Issue', DESCR = '일반 업무', ICON = 'issue', MODIFIED_AT = now()
WHERE TYPE_NM = 'Task' AND NOT EXISTS (SELECT 1 FROM SN_CIRA_CIRA_ISSUE_TYPE WHERE TYPE_NM = 'Issue');

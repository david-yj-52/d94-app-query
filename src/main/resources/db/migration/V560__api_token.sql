-- =============================================================
-- API 토큰 (MCP·AI 도구용). 원문은 저장하지 않고 SHA-256 hex 만 둔다.
-- 설계: d94-note feature/user/3_api_token/api-token-plan.md
-- =============================================================

CREATE TABLE IF NOT EXISTS SN_API_TOKEN
(
    OBJ_ID       VARCHAR(100) NOT NULL,
    OWNER_ID     VARCHAR(200) NOT NULL,
    SERVICE_CD   VARCHAR(40)  NOT NULL,
    TOKEN_NM     VARCHAR(100) NOT NULL,
    TOKEN_HASH   CHAR(64)     NOT NULL,
    TOKEN_PREFIX VARCHAR(20)  NOT NULL,
    ACCESS_CD    VARCHAR(10)  NOT NULL,
    EXPIRES_AT   TIMESTAMP    NOT NULL,
    LAST_USED_AT TIMESTAMP,
    REVOKED_AT   TIMESTAMP,
    -- BaseModel
    SRV_ID       VARCHAR(50)  NOT NULL,
    TENANT       VARCHAR(50)  NOT NULL,
    TRACE_ID     VARCHAR(100) NOT NULL,
    USE_STAT_CD  VARCHAR(40)  NOT NULL DEFAULT 'Usable',
    EVNT_NM      VARCHAR(100) NOT NULL,
    PREV_EVNT_NM VARCHAR(100) NOT NULL,
    ACT_CD       VARCHAR(255),
    ACT_CM       VARCHAR(255),
    CREATED_BY   VARCHAR(40),
    CREATED_AT   TIMESTAMP    NOT NULL DEFAULT NOW(),
    MODIFIED_BY  VARCHAR(40),
    MODIFIED_AT  TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT PK_SN_API_TOKEN PRIMARY KEY (OBJ_ID),
    CONSTRAINT uk_sn_api_token_01 UNIQUE (TOKEN_HASH)
);

CREATE INDEX IF NOT EXISTS ix_sn_api_token_01 ON SN_API_TOKEN (TENANT, OWNER_ID);

COMMENT ON TABLE SN_API_TOKEN IS 'API 토큰. 발급 사용자(OWNER_ID=이메일)로 동작, SERVICE_CD 경로만, ACCESS_CD READ=GET/HEAD';
COMMENT ON COLUMN SN_API_TOKEN.TOKEN_HASH IS 'SHA-256(원문) hex. 원문은 발급 응답에 1회만';
COMMENT ON COLUMN SN_API_TOKEN.TOKEN_PREFIX IS '화면 표시용 원문 앞 12자';
COMMENT ON COLUMN SN_API_TOKEN.REVOKED_AT IS '폐기 시각. NULL 이 아니면 무효';
